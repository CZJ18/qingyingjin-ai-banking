CREATE TABLE IF NOT EXISTS banking_agent_jobs (
 id VARCHAR(36) COLLATE qyj_mysql_ci NOT NULL PRIMARY KEY,
 user_id BIGINT NOT NULL,
 status VARCHAR(32) COLLATE qyj_mysql_ci NOT NULL,
 strategy VARCHAR(24) COLLATE qyj_mysql_ci NOT NULL,
 version BIGINT NOT NULL,
 max_attempts INT NOT NULL,
 timeout_ms BIGINT NOT NULL,
 use_coze BOOLEAN NOT NULL,
 source_plan_id VARCHAR(128) COLLATE qyj_mysql_ci NOT NULL,
 request_hash VARCHAR(64) COLLATE qyj_mysql_ci NOT NULL,
 idempotency_key VARCHAR(128) COLLATE qyj_mysql_ci NOT NULL,
 lease_token VARCHAR(36) COLLATE qyj_mysql_ci NOT NULL,
 lease_until BIGINT NOT NULL,
 trace_id VARCHAR(128) COLLATE qyj_mysql_ci NOT NULL,
 audit_id VARCHAR(36) COLLATE qyj_mysql_ci NOT NULL,
 created_at BIGINT NOT NULL,
 updated_at BIGINT NOT NULL,
 CONSTRAINT agent_jobs_uq_job_owner UNIQUE (user_id,id),
 CONSTRAINT agent_jobs_uq_job_idempotency UNIQUE (user_id,idempotency_key),
 CONSTRAINT fk_job_user FOREIGN KEY(user_id) REFERENCES banking_users(id),
 CONSTRAINT ck_job_attempts CHECK(max_attempts BETWEEN 1 AND 3),
 CONSTRAINT ck_job_timeout CHECK(timeout_ms BETWEEN 100 AND 60000)
);
CREATE INDEX agent_jobs_ix_job_queue ON banking_agent_jobs (status,lease_until,created_at);
CREATE TABLE IF NOT EXISTS banking_agent_tasks (
 id VARCHAR(36) COLLATE qyj_mysql_ci NOT NULL PRIMARY KEY,
 user_id BIGINT NOT NULL,
 job_id VARCHAR(36) COLLATE qyj_mysql_ci NOT NULL,
 task_key VARCHAR(64) COLLATE qyj_mysql_ci NOT NULL,
 agent_type VARCHAR(24) COLLATE qyj_mysql_ci NOT NULL,
 tool VARCHAR(64) COLLATE qyj_mysql_ci NOT NULL,
 mode VARCHAR(24) COLLATE qyj_mysql_ci NOT NULL,
 priority INT NOT NULL,
 status VARCHAR(32) COLLATE qyj_mysql_ci NOT NULL,
 parameters_json JSONB NOT NULL,
 output_json JSONB NOT NULL,
 attempts INT NOT NULL,
 retry_at BIGINT NOT NULL,
 confirmation VARCHAR(16) COLLATE qyj_mysql_ci NOT NULL,
 error_code VARCHAR(64) COLLATE qyj_mysql_ci NOT NULL,
 protected_blocked BOOLEAN NOT NULL DEFAULT FALSE,
 created_at BIGINT NOT NULL,
 updated_at BIGINT NOT NULL,
 CONSTRAINT agent_tasks_uq_task_owner UNIQUE (user_id,id),
 CONSTRAINT agent_tasks_uq_job_task_key UNIQUE (job_id,task_key),
 CONSTRAINT fk_task_job FOREIGN KEY(user_id,job_id) REFERENCES banking_agent_jobs(user_id,id)
);

CREATE TABLE IF NOT EXISTS banking_agent_dependencies (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
 user_id BIGINT NOT NULL,
 job_id VARCHAR(36) COLLATE qyj_mysql_ci NOT NULL,
 task_id VARCHAR(36) COLLATE qyj_mysql_ci NOT NULL,
 depends_on VARCHAR(36) COLLATE qyj_mysql_ci NOT NULL,
 CONSTRAINT agent_dependencies_uq_agent_dependency UNIQUE (task_id,depends_on),
 CONSTRAINT fk_dependency_job FOREIGN KEY(user_id,job_id) REFERENCES banking_agent_jobs(user_id,id),
 CONSTRAINT fk_dependency_task FOREIGN KEY(user_id,task_id) REFERENCES banking_agent_tasks(user_id,id),
 CONSTRAINT fk_dependency_parent FOREIGN KEY(user_id,depends_on) REFERENCES banking_agent_tasks(user_id,id)
);

CREATE TABLE IF NOT EXISTS banking_agent_executions (
 id VARCHAR(36) COLLATE qyj_mysql_ci NOT NULL PRIMARY KEY,
 user_id BIGINT NOT NULL,
 job_id VARCHAR(36) COLLATE qyj_mysql_ci NOT NULL,
 task_id VARCHAR(36) COLLATE qyj_mysql_ci NOT NULL,
 agent_type VARCHAR(24) COLLATE qyj_mysql_ci NOT NULL,
 attempt INT NOT NULL,
 status VARCHAR(32) COLLATE qyj_mysql_ci NOT NULL,
 started_at BIGINT NOT NULL,
 finished_at BIGINT NOT NULL,
 duration_ms BIGINT NOT NULL,
 error_code VARCHAR(64) COLLATE qyj_mysql_ci NOT NULL,
 workflow_execute_id VARCHAR(128) COLLATE qyj_mysql_ci NOT NULL,
 input_json JSONB NOT NULL,
 output_json JSONB NOT NULL,
 lease_token VARCHAR(36) COLLATE qyj_mysql_ci NOT NULL,
 CONSTRAINT agent_executions_uq_execution_owner UNIQUE (user_id,id),
 CONSTRAINT agent_executions_uq_task_attempt UNIQUE (task_id,attempt),
 CONSTRAINT fk_execution_job FOREIGN KEY(user_id,job_id) REFERENCES banking_agent_jobs(user_id,id),
 CONSTRAINT fk_execution_task FOREIGN KEY(user_id,task_id) REFERENCES banking_agent_tasks(user_id,id)
);

CREATE TABLE IF NOT EXISTS banking_tool_invocations (
 id VARCHAR(36) COLLATE qyj_mysql_ci NOT NULL PRIMARY KEY,
 user_id BIGINT NOT NULL,
 job_id VARCHAR(36) COLLATE qyj_mysql_ci NOT NULL,
 task_id VARCHAR(36) COLLATE qyj_mysql_ci NOT NULL,
 execution_id VARCHAR(36) COLLATE qyj_mysql_ci NOT NULL,
 tool VARCHAR(64) COLLATE qyj_mysql_ci NOT NULL,
 invocation_key VARCHAR(128) COLLATE qyj_mysql_ci NOT NULL,
 status VARCHAR(32) COLLATE qyj_mysql_ci NOT NULL,
 started_at BIGINT NOT NULL,
 finished_at BIGINT NOT NULL,
 duration_ms BIGINT NOT NULL,
 error_code VARCHAR(64) COLLATE qyj_mysql_ci NOT NULL,
 audit_id VARCHAR(36) COLLATE qyj_mysql_ci NOT NULL,
 CONSTRAINT tool_invocations_uq_invocation_execution UNIQUE (execution_id),
 CONSTRAINT fk_invocation_job FOREIGN KEY(user_id,job_id) REFERENCES banking_agent_jobs(user_id,id),
 CONSTRAINT fk_invocation_task FOREIGN KEY(user_id,task_id) REFERENCES banking_agent_tasks(user_id,id),
 CONSTRAINT fk_invocation_execution FOREIGN KEY(user_id,execution_id) REFERENCES banking_agent_executions(user_id,id)
);

CREATE TABLE IF NOT EXISTS banking_execution_traces (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
 user_id BIGINT NOT NULL,
 job_id VARCHAR(36) COLLATE qyj_mysql_ci NOT NULL,
 task_id VARCHAR(36) COLLATE qyj_mysql_ci NOT NULL,
 event VARCHAR(48) COLLATE qyj_mysql_ci NOT NULL,
 status VARCHAR(32) COLLATE qyj_mysql_ci NOT NULL,
 error_code VARCHAR(64) COLLATE qyj_mysql_ci NOT NULL,
 audit_id VARCHAR(36) COLLATE qyj_mysql_ci NOT NULL,
 trace_id VARCHAR(128) COLLATE qyj_mysql_ci NOT NULL,
 created_at BIGINT NOT NULL,
 CONSTRAINT fk_trace_job FOREIGN KEY(user_id,job_id) REFERENCES banking_agent_jobs(user_id,id)
);
CREATE INDEX execution_traces_ix_job_events ON banking_execution_traces (user_id,job_id,id);

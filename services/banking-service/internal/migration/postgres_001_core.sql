CREATE COLLATION IF NOT EXISTS qyj_mysql_ci (provider = icu, locale = 'und-u-ks-level1', deterministic = false);
CREATE TABLE IF NOT EXISTS banking_users (
 id BIGINT NOT NULL PRIMARY KEY,
 display_name VARCHAR(128) COLLATE qyj_mysql_ci NOT NULL,
 status VARCHAR(16) COLLATE qyj_mysql_ci NOT NULL,
 created_at BIGINT NOT NULL,
 updated_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS banking_bank_accounts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
 user_id BIGINT NOT NULL,
 external_account_id VARCHAR(128) COLLATE qyj_mysql_ci NULL,
 display_name VARCHAR(128) COLLATE qyj_mysql_ci NOT NULL,
 account_type VARCHAR(32) COLLATE qyj_mysql_ci NOT NULL,
 masked_account_number VARCHAR(32) COLLATE qyj_mysql_ci NOT NULL,
 currency VARCHAR(3) COLLATE qyj_mysql_ci NOT NULL,
 balance_minor BIGINT NOT NULL DEFAULT 0,
 status VARCHAR(16) COLLATE qyj_mysql_ci NOT NULL,
 version BIGINT NOT NULL DEFAULT 1,
 is_simulated BOOLEAN NOT NULL DEFAULT TRUE,
 savings_goal_id BIGINT NULL,
 created_at BIGINT NOT NULL,
 updated_at BIGINT NOT NULL,
 CONSTRAINT bank_accounts_uq_account_owner UNIQUE (user_id,id),
 CONSTRAINT bank_accounts_uq_account_external UNIQUE (user_id,external_account_id),
 CONSTRAINT fk_account_user FOREIGN KEY (user_id) REFERENCES banking_users(id),
 CONSTRAINT ck_balance CHECK (balance_minor >= 0 AND balance_minor <= 1000000000000),
 CONSTRAINT ck_account_status CHECK (status IN ('active','frozen','inactive','closed')),
 CONSTRAINT ck_account_simulated CHECK (is_simulated = TRUE)
);

CREATE TABLE IF NOT EXISTS banking_transactions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
 user_id BIGINT NOT NULL,
 bank_account_id BIGINT NOT NULL,
 external_transaction_id VARCHAR(128) COLLATE qyj_mysql_ci NULL,
 direction VARCHAR(16) COLLATE qyj_mysql_ci NOT NULL,
 amount_minor BIGINT NOT NULL,
 currency VARCHAR(3) COLLATE qyj_mysql_ci NOT NULL,
 category VARCHAR(64) COLLATE qyj_mysql_ci NOT NULL,
 merchant_name VARCHAR(128) COLLATE qyj_mysql_ci NOT NULL,
 description VARCHAR(512) COLLATE qyj_mysql_ci NOT NULL,
 occurred_at BIGINT NOT NULL,
 source_metadata JSONB NULL,
 kind VARCHAR(32) COLLATE qyj_mysql_ci NOT NULL,
 effect_mode VARCHAR(32) COLLATE qyj_mysql_ci NOT NULL,
 journal_id VARCHAR(36) COLLATE qyj_mysql_ci NULL,
 transfer_id BIGINT NULL,
 trace_id VARCHAR(128) COLLATE qyj_mysql_ci NOT NULL,
 task_id VARCHAR(128) COLLATE qyj_mysql_ci NOT NULL,
 audit_id VARCHAR(36) COLLATE qyj_mysql_ci NOT NULL,
 created_at BIGINT NOT NULL,
 updated_at BIGINT NOT NULL,
 CONSTRAINT transactions_uq_external_transaction UNIQUE (user_id,bank_account_id,external_transaction_id),
 CONSTRAINT fk_transaction_account FOREIGN KEY (user_id,bank_account_id) REFERENCES banking_bank_accounts(user_id,id),
 CONSTRAINT ck_transaction_amount CHECK (amount_minor > 0 AND amount_minor <= 1000000000000),
 CONSTRAINT ck_direction CHECK (direction IN ('income','expense'))
);
CREATE INDEX transactions_ix_transaction_period ON banking_transactions (user_id,occurred_at,id);
CREATE INDEX transactions_ix_transaction_category ON banking_transactions (user_id,category,occurred_at);
CREATE TABLE IF NOT EXISTS banking_ledger_entries (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
 user_id BIGINT NOT NULL,
 journal_id VARCHAR(36) COLLATE qyj_mysql_ci NOT NULL,
 sequence INT NOT NULL,
 account_id BIGINT NULL,
 transaction_id BIGINT NULL,
 currency VARCHAR(3) COLLATE qyj_mysql_ci NOT NULL,
 delta_minor BIGINT NOT NULL,
 side VARCHAR(8) COLLATE qyj_mysql_ci NOT NULL,
 created_at BIGINT NOT NULL,
 CONSTRAINT ledger_entries_uq_journal_leg UNIQUE (journal_id,sequence),
 CONSTRAINT fk_ledger_account FOREIGN KEY (user_id,account_id) REFERENCES banking_bank_accounts(user_id,id),
 CONSTRAINT fk_ledger_transaction FOREIGN KEY (transaction_id) REFERENCES banking_transactions(id),
 CONSTRAINT ck_ledger_sequence CHECK (sequence IN (1,2)),
 CONSTRAINT ck_ledger_delta CHECK (delta_minor <> 0 AND delta_minor BETWEEN -1000000000000 AND 1000000000000),
 CONSTRAINT ck_ledger_side CHECK ((side='debit' AND delta_minor>0) OR (side='credit' AND delta_minor<0))
);
CREATE INDEX ledger_entries_ix_ledger_account ON banking_ledger_entries (user_id,account_id,id);
CREATE TABLE IF NOT EXISTS banking_core_audits (
 id VARCHAR(36) COLLATE qyj_mysql_ci NOT NULL PRIMARY KEY,
 user_id BIGINT NOT NULL,
 action VARCHAR(64) COLLATE qyj_mysql_ci NOT NULL,
 resource_id BIGINT NOT NULL,
 outcome VARCHAR(16) COLLATE qyj_mysql_ci NOT NULL,
 trace_id VARCHAR(128) COLLATE qyj_mysql_ci NOT NULL,
 task_id VARCHAR(128) COLLATE qyj_mysql_ci NOT NULL,
 error_code VARCHAR(64) COLLATE qyj_mysql_ci NOT NULL,
 created_at BIGINT NOT NULL
);
CREATE INDEX core_audits_ix_audit_user ON banking_core_audits (user_id,created_at,id);
CREATE TABLE IF NOT EXISTS banking_core_idempotency (
 user_id BIGINT NOT NULL,
 action VARCHAR(64) COLLATE qyj_mysql_ci NOT NULL,
 idem_key VARCHAR(128) COLLATE "C" NOT NULL,
 request_hash VARCHAR(64) COLLATE qyj_mysql_ci NOT NULL,
 response BYTEA NULL,
 created_at BIGINT NOT NULL,
 PRIMARY KEY (user_id,action,idem_key)
);

CREATE TABLE IF NOT EXISTS banking_transfer_intents (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
 user_id BIGINT NOT NULL,
 source_account_id BIGINT NOT NULL,
 target_account_id BIGINT NOT NULL,
 amount_minor BIGINT NOT NULL,
 currency VARCHAR(3) COLLATE qyj_mysql_ci NOT NULL,
 description VARCHAR(512) COLLATE qyj_mysql_ci NOT NULL,
 purpose VARCHAR(32) COLLATE qyj_mysql_ci NOT NULL,
 savings_goal_id BIGINT NULL,
 status VARCHAR(32) COLLATE qyj_mysql_ci NOT NULL,
 approval_hash VARCHAR(64) COLLATE qyj_mysql_ci NOT NULL,
 expires_at BIGINT NOT NULL,
 journal_id VARCHAR(36) COLLATE qyj_mysql_ci NOT NULL,
 failure_code VARCHAR(64) COLLATE qyj_mysql_ci NOT NULL,
 audit_id VARCHAR(36) COLLATE qyj_mysql_ci NOT NULL,
 trace_id VARCHAR(128) COLLATE qyj_mysql_ci NOT NULL,
 task_id VARCHAR(128) COLLATE qyj_mysql_ci NOT NULL,
 created_at BIGINT NOT NULL,
 updated_at BIGINT NOT NULL,
 CONSTRAINT fk_transfer_source FOREIGN KEY (user_id,source_account_id) REFERENCES banking_bank_accounts(user_id,id),
 CONSTRAINT fk_transfer_target FOREIGN KEY (user_id,target_account_id) REFERENCES banking_bank_accounts(user_id,id),
 CONSTRAINT ck_transfer_amount CHECK (amount_minor>0 AND amount_minor<=1000000000000),
 CONSTRAINT ck_transfer_accounts CHECK (source_account_id<>target_account_id),
 CONSTRAINT ck_transfer_status CHECK (status IN ('pending_approval','succeeded','failed','rejected'))
);
CREATE INDEX transfer_intents_ix_transfer_user ON banking_transfer_intents (user_id,id);
CREATE TABLE IF NOT EXISTS banking_transfer_approvals (
 transfer_id BIGINT NOT NULL PRIMARY KEY,
 user_id BIGINT NOT NULL,
 decision VARCHAR(16) COLLATE qyj_mysql_ci NOT NULL,
 approval_hash VARCHAR(64) COLLATE qyj_mysql_ci NOT NULL,
 expires_at BIGINT NOT NULL,
 consumed_at BIGINT NOT NULL,
 created_at BIGINT NOT NULL,
 CONSTRAINT fk_approval_transfer FOREIGN KEY (transfer_id) REFERENCES banking_transfer_intents(id)
);

CREATE TABLE IF NOT EXISTS banking_budgets (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
 user_id BIGINT NOT NULL,
 month VARCHAR(7) COLLATE qyj_mysql_ci NOT NULL,
 currency VARCHAR(3) COLLATE qyj_mysql_ci NOT NULL,
 total_minor BIGINT NOT NULL,
 created_at BIGINT NOT NULL,
 updated_at BIGINT NOT NULL,
 CONSTRAINT budgets_uq_budget_month UNIQUE (user_id,month,currency),
 CONSTRAINT budgets_uq_budget_owner UNIQUE (user_id,id),
 CONSTRAINT fk_budget_user FOREIGN KEY (user_id) REFERENCES banking_users(id),
 CONSTRAINT ck_budget_amount CHECK (total_minor>0 AND total_minor<=1000000000000)
);

CREATE TABLE IF NOT EXISTS banking_budget_categories (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
 user_id BIGINT NOT NULL,
 budget_id BIGINT NOT NULL,
 category VARCHAR(64) COLLATE qyj_mysql_ci NOT NULL,
 allocated_minor BIGINT NOT NULL,
 essential_reserve_minor BIGINT NOT NULL,
 CONSTRAINT budget_categories_uq_budget_category UNIQUE (budget_id,category),
 CONSTRAINT fk_category_budget FOREIGN KEY (user_id,budget_id) REFERENCES banking_budgets(user_id,id),
 CONSTRAINT ck_category_amount CHECK (allocated_minor>=0 AND allocated_minor<=1000000000000 AND essential_reserve_minor>=0 AND essential_reserve_minor<=allocated_minor)
);

CREATE TABLE IF NOT EXISTS banking_budget_rules (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
 user_id BIGINT NOT NULL,
 budget_id BIGINT NOT NULL,
 kind VARCHAR(32) COLLATE qyj_mysql_ci NOT NULL,
 enabled BOOLEAN NOT NULL,
 CONSTRAINT budget_rules_uq_budget_rule UNIQUE (budget_id,kind),
 CONSTRAINT fk_rule_budget FOREIGN KEY (user_id,budget_id) REFERENCES banking_budgets(user_id,id)
);

CREATE TABLE IF NOT EXISTS banking_savings_goals (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
 user_id BIGINT NOT NULL,
 name VARCHAR(128) COLLATE qyj_mysql_ci NOT NULL,
 target_minor BIGINT NOT NULL,
 currency VARCHAR(3) COLLATE qyj_mysql_ci NOT NULL,
 starts_at BIGINT NOT NULL,
 ends_at BIGINT NOT NULL,
 account_id BIGINT NOT NULL,
 status VARCHAR(16) COLLATE qyj_mysql_ci NOT NULL,
 created_at BIGINT NOT NULL,
 updated_at BIGINT NOT NULL,
 CONSTRAINT savings_goals_uq_goal_account UNIQUE (account_id),
 CONSTRAINT savings_goals_uq_goal_owner UNIQUE (user_id,id),
 CONSTRAINT fk_goal_account FOREIGN KEY (user_id,account_id) REFERENCES banking_bank_accounts(user_id,id),
 CONSTRAINT ck_goal_target CHECK (target_minor>0 AND target_minor<=1000000000000),
 CONSTRAINT ck_goal_period CHECK (ends_at>starts_at)
);

CREATE TABLE IF NOT EXISTS banking_savings_plans (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
 user_id BIGINT NOT NULL,
 goal_id BIGINT NOT NULL,
 monthly_minor BIGINT NOT NULL,
 cadence VARCHAR(16) COLLATE qyj_mysql_ci NOT NULL,
 status VARCHAR(16) COLLATE qyj_mysql_ci NOT NULL,
 CONSTRAINT savings_plans_uq_goal_plan UNIQUE (goal_id),
 CONSTRAINT fk_plan_goal FOREIGN KEY (user_id,goal_id) REFERENCES banking_savings_goals(user_id,id),
 CONSTRAINT ck_plan_amount CHECK (monthly_minor>0 AND monthly_minor<=1000000000000)
);

CREATE TABLE IF NOT EXISTS banking_savings_ledgers (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
 user_id BIGINT NOT NULL,
 goal_id BIGINT NOT NULL,
 transfer_id BIGINT NOT NULL,
 journal_id VARCHAR(36) COLLATE qyj_mysql_ci NOT NULL,
 delta_minor BIGINT NOT NULL,
 currency VARCHAR(3) COLLATE qyj_mysql_ci NOT NULL,
 created_at BIGINT NOT NULL,
 CONSTRAINT savings_ledgers_uq_savings_transfer UNIQUE (transfer_id),
 CONSTRAINT fk_savings_goal FOREIGN KEY (user_id,goal_id) REFERENCES banking_savings_goals(user_id,id),
 CONSTRAINT fk_savings_transfer FOREIGN KEY (transfer_id) REFERENCES banking_transfer_intents(id)
);
CREATE INDEX savings_ledgers_ix_savings_goal ON banking_savings_ledgers (user_id,goal_id,id);

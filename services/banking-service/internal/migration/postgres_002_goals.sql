CREATE TABLE IF NOT EXISTS banking_life_goals (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
 user_id BIGINT NOT NULL,
 current_version BIGINT NOT NULL,
 status VARCHAR(32) COLLATE qyj_mysql_ci NOT NULL,
 created_at BIGINT NOT NULL,
 updated_at BIGINT NOT NULL,
 CONSTRAINT life_goals_uq_life_goal_owner UNIQUE (id,user_id),
 CONSTRAINT fk_life_goal_user FOREIGN KEY(user_id) REFERENCES banking_users(id)
);
CREATE INDEX life_goals_ix_life_goal_user ON banking_life_goals (user_id,id);
CREATE TABLE IF NOT EXISTS banking_goal_versions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
 user_id BIGINT NOT NULL,
 goal_id BIGINT NOT NULL,
 version BIGINT NOT NULL,
 text TEXT NOT NULL,
 context_json JSONB NOT NULL,
 parsed_json JSONB NULL,
 parse_status VARCHAR(32) COLLATE qyj_mysql_ci NOT NULL,
 parse_id VARCHAR(64) COLLATE qyj_mysql_ci NOT NULL DEFAULT '',
 lease_until BIGINT NOT NULL DEFAULT 0,
 workflow_id VARCHAR(64) COLLATE qyj_mysql_ci NOT NULL DEFAULT '',
 execute_id VARCHAR(64) COLLATE qyj_mysql_ci NOT NULL DEFAULT '',
 error_code VARCHAR(64) COLLATE qyj_mysql_ci NOT NULL DEFAULT '',
 trace_id VARCHAR(128) COLLATE qyj_mysql_ci NOT NULL,
 audit_id VARCHAR(64) COLLATE qyj_mysql_ci NOT NULL,
 created_at BIGINT NOT NULL,
 updated_at BIGINT NOT NULL,
 CONSTRAINT goal_versions_uq_goal_version UNIQUE (goal_id,version),
 CONSTRAINT goal_versions_uq_goal_version_owner UNIQUE (id,user_id),
 CONSTRAINT fk_goal_version_owner FOREIGN KEY(goal_id,user_id) REFERENCES banking_life_goals(id,user_id)
);

CREATE TABLE IF NOT EXISTS banking_goal_constraints (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
 user_id BIGINT NOT NULL,
 goal_version_id BIGINT NOT NULL,
 kind VARCHAR(32) COLLATE qyj_mysql_ci NOT NULL,
 description TEXT NOT NULL,
 evidence TEXT NOT NULL,
 created_at BIGINT NOT NULL,
 updated_at BIGINT NOT NULL,
 CONSTRAINT fk_goal_constraint_owner FOREIGN KEY(goal_version_id,user_id) REFERENCES banking_goal_versions(id,user_id)
);
CREATE INDEX goal_constraints_ix_goal_constraint_version ON banking_goal_constraints (goal_version_id,user_id);
CREATE TABLE IF NOT EXISTS banking_task_plans (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
 user_id BIGINT NOT NULL,
 goal_id BIGINT NOT NULL,
 goal_version_id BIGINT NOT NULL,
 version BIGINT NOT NULL,
 status VARCHAR(32) COLLATE qyj_mysql_ci NOT NULL,
 plan_json JSONB NOT NULL,
 trace_id VARCHAR(128) COLLATE qyj_mysql_ci NOT NULL,
 audit_id VARCHAR(64) COLLATE qyj_mysql_ci NOT NULL,
 created_at BIGINT NOT NULL,
 updated_at BIGINT NOT NULL,
 CONSTRAINT task_plans_uq_task_plan_version UNIQUE (goal_version_id),
 CONSTRAINT task_plans_uq_task_plan_owner UNIQUE (id,user_id),
 CONSTRAINT fk_task_plan_version_owner FOREIGN KEY(goal_version_id,user_id) REFERENCES banking_goal_versions(id,user_id),
 CONSTRAINT fk_task_plan_goal_owner FOREIGN KEY(goal_id,user_id) REFERENCES banking_life_goals(id,user_id)
);
CREATE INDEX task_plans_ix_task_plan_goal ON banking_task_plans (goal_id,user_id);
CREATE TABLE IF NOT EXISTS banking_task_dependencies (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
 user_id BIGINT NOT NULL,
 plan_id BIGINT NOT NULL,
 task_id VARCHAR(64) COLLATE qyj_mysql_ci NOT NULL,
 depends_on VARCHAR(64) COLLATE qyj_mysql_ci NOT NULL,
 created_at BIGINT NOT NULL,
 updated_at BIGINT NOT NULL,
 CONSTRAINT task_dependencies_uq_task_dependency UNIQUE (plan_id,task_id,depends_on),
 CONSTRAINT fk_task_dependency_owner FOREIGN KEY(plan_id,user_id) REFERENCES banking_task_plans(id,user_id)
);


CREATE TABLE IF NOT EXISTS banking_lifestyle_goals (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
 user_id BIGINT NOT NULL,
 current_version BIGINT NOT NULL,
 created_at BIGINT NOT NULL,
 updated_at BIGINT NOT NULL,
 CONSTRAINT lifestyle_goals_lifestyle_goal_owner UNIQUE (id,user_id),
 FOREIGN KEY(user_id) REFERENCES banking_users(id)
);
CREATE INDEX lifestyle_goals_lifestyle_goal_user ON banking_lifestyle_goals (user_id);
CREATE TABLE IF NOT EXISTS banking_lifestyle_goal_versions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
 user_id BIGINT NOT NULL,
 goal_id BIGINT NOT NULL,
 version BIGINT NOT NULL,
 text TEXT NOT NULL,
 spec_json JSONB NOT NULL,
 trace_id VARCHAR(128) COLLATE qyj_mysql_ci NOT NULL,
 created_at BIGINT NOT NULL,
 updated_at BIGINT NOT NULL,
 CONSTRAINT lifestyle_goal_versions_lifestyle_goal_version UNIQUE (goal_id,version),
 FOREIGN KEY(goal_id,user_id) REFERENCES banking_lifestyle_goals(id,user_id)
);

CREATE TABLE IF NOT EXISTS banking_lifestyle_plans (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
 user_id BIGINT NOT NULL,
 goal_id BIGINT NOT NULL,
 goal_version BIGINT NOT NULL,
 input_digest VARCHAR(64) COLLATE qyj_mysql_ci NOT NULL,
 snapshot_json JSONB NOT NULL,
 result_json JSONB NOT NULL,
 expires_at BIGINT NOT NULL,
 audit_id VARCHAR(36) COLLATE qyj_mysql_ci NOT NULL,
 trace_id VARCHAR(128) COLLATE qyj_mysql_ci NOT NULL,
 created_at BIGINT NOT NULL,
 updated_at BIGINT NOT NULL,
 CONSTRAINT lifestyle_plans_lifestyle_plan_owner UNIQUE (id,user_id),
 FOREIGN KEY(goal_id,user_id) REFERENCES banking_lifestyle_goals(id,user_id)
);
CREATE INDEX lifestyle_plans_lifestyle_plan_goal ON banking_lifestyle_plans (goal_id,id);
CREATE TABLE IF NOT EXISTS banking_lifestyle_recommendations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
 user_id BIGINT NOT NULL,
 goal_id BIGINT NOT NULL,
 plan_id BIGINT NOT NULL,
 type VARCHAR(64) COLLATE qyj_mysql_ci NOT NULL,
 expected_impact_minor BIGINT NOT NULL,
 impact_period VARCHAR(32) COLLATE qyj_mysql_ci NOT NULL,
 explanation TEXT NOT NULL,
 confidence VARCHAR(64) COLLATE qyj_mysql_ci NOT NULL,
 status VARCHAR(32) COLLATE qyj_mysql_ci NOT NULL,
 version BIGINT NOT NULL,
 expires_at BIGINT NOT NULL,
 rule_version VARCHAR(64) COLLATE qyj_mysql_ci NOT NULL,
 option_json JSONB NOT NULL,
 created_at BIGINT NOT NULL,
 updated_at BIGINT NOT NULL,
 CONSTRAINT lifestyle_recommendations_lifestyle_rec_owner UNIQUE (id,user_id),
 CONSTRAINT lifestyle_recommendations_lifestyle_rec_option UNIQUE (plan_id,type),
 FOREIGN KEY(plan_id,user_id) REFERENCES banking_lifestyle_plans(id,user_id),
 FOREIGN KEY(goal_id,user_id) REFERENCES banking_lifestyle_goals(id,user_id),
 CHECK(expected_impact_minor >= 0)
);
CREATE INDEX lifestyle_recommendations_lifestyle_rec_goal ON banking_lifestyle_recommendations (user_id,goal_id,status);
CREATE TABLE IF NOT EXISTS banking_lifestyle_decisions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
 user_id BIGINT NOT NULL,
 recommendation_id BIGINT NOT NULL,
 decision VARCHAR(16) COLLATE qyj_mysql_ci NOT NULL,
 request_key VARCHAR(128) COLLATE qyj_mysql_ci NOT NULL,
 input_digest VARCHAR(64) COLLATE qyj_mysql_ci NOT NULL,
 audit_id VARCHAR(36) COLLATE qyj_mysql_ci NOT NULL,
 trace_id VARCHAR(128) COLLATE qyj_mysql_ci NOT NULL,
 created_at BIGINT NOT NULL,
 updated_at BIGINT NOT NULL,
 CONSTRAINT lifestyle_decisions_lifestyle_rec_decision UNIQUE (recommendation_id),
 FOREIGN KEY(recommendation_id,user_id) REFERENCES banking_lifestyle_recommendations(id,user_id)
);


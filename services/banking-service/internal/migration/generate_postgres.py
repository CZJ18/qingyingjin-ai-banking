"""Regenerate the reviewed PostgreSQL baseline from immutable MySQL migrations.

This is a development tool, never runtime SQL rewriting. Review generated SQL and
run the PostgreSQL integration suite after changing this file or source DDL.
"""

from pathlib import Path
import hashlib
import re

ROOT = Path(__file__).resolve().parent


def parts(text):
    result, start, depth, quoted = [], 0, 0, False
    for pos, char in enumerate(text):
        if char == "'":
            quoted = not quoted
        if not quoted:
            depth += char == "("
            depth -= char == ")"
            if char == "," and depth == 0:
                result.append(text[start:pos].strip())
                start = pos + 1
    result.append(text[start:].strip())
    return result


def index_name(table, original):
    name = table.removeprefix("banking_") + "_" + original
    if len(name) > 63:
        name = name[:54] + "_" + hashlib.sha256(name.encode()).hexdigest()[:8]
    return name


def table_ddl(match):
    table, body = match.groups()
    columns, indexes = [], []
    for item in parts(body):
        unique = re.fullmatch(r"UNIQUE KEY (\w+)\s*(\(.+\))", item, re.S)
        index = re.fullmatch(r"KEY (\w+)\s*(\(.+\))", item, re.S)
        if unique:
            columns.append(f"CONSTRAINT {index_name(table, unique[1])} UNIQUE {unique[2]}")
        elif index:
            indexes.append(f"CREATE INDEX {index_name(table, index[1])} ON {table} {index[2]};")
        else:
            item = item.replace("BIGINT NOT NULL AUTO_INCREMENT", "BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL")
            item = re.sub(r"\bJSON\b", "JSONB", item).replace("LONGBLOB", "BYTEA")
            # VARCHAR mirrors MySQL CHAR's unpadded driver result and length bound.
            item = re.sub(r"\bCHAR\((\d+)\)", r"VARCHAR(\1)", item)
            binary = "COLLATE utf8mb4_bin" in item
            item = item.replace(" COLLATE utf8mb4_bin", "")
            item = re.sub(r"\b(VARCHAR\(\d+\))", r'\1 COLLATE "C"' if binary else r"\1 COLLATE qyj_mysql_ci", item)
            item = item.replace("`", '"')
            columns.append(item)
    return "CREATE TABLE IF NOT EXISTS " + table + " (\n " + ",\n ".join(columns) + "\n);\n" + "\n".join(indexes)


TRIGGER_FUNCTION = """
-- Transactional outbox: a rollback also removes the replan event.
CREATE OR REPLACE FUNCTION qyj_emit_replan_event() RETURNS trigger
LANGUAGE plpgsql AS $qyj$
DECLARE
 event_time BIGINT := floor(extract(epoch FROM clock_timestamp()) * 1000)::BIGINT;
BEGIN
 -- Only the control-table owner (or a member of that owner role) may suppress
 -- derived events during an audited import. A runtime-set custom GUC alone
 -- does not authorize bypass, and the control relation uses the trigger's
 -- schema rather than a caller-controlled search_path or temporary table.
 IF current_setting('banking.migration_import',true)='on' AND
    pg_has_role(session_user,pg_get_userbyid((SELECT relowner FROM pg_class
      WHERE oid=to_regclass(format('%I.banking_storage_control',TG_TABLE_SCHEMA)))),'MEMBER') THEN
   RETURN NEW;
 END IF;
 INSERT INTO banking_replan_events(user_id,event_key,type,resource_id,reason,trace_id,task_id,created_at,updated_at)
 VALUES (NEW.user_id,gen_random_uuid()::TEXT,TG_ARGV[0],NEW.id::TEXT,TG_TABLE_NAME || ':' || lower(TG_OP),
         CASE WHEN TG_ARGV[1]='trace_id' THEN to_jsonb(NEW)->>'trace_id' ELSE '' END,
         CASE WHEN TG_ARGV[2]='task_id' THEN to_jsonb(NEW)->>'task_id' ELSE '' END,event_time,event_time);
 RETURN NEW;
END;
$qyj$;
"""


def trigger_ddl(match):
    name, operation, table, event_type, trace, task = match.groups()
    condition = ""
    if table == "banking_bank_accounts" and operation == "UPDATE":
        condition = " WHEN (OLD.balance_minor IS DISTINCT FROM NEW.balance_minor OR OLD.status IS DISTINCT FROM NEW.status)"
    trace = "trace_id" if trace == "NEW.trace_id" else ""
    task = "task_id" if task == "NEW.task_id" else ""
    return (f"CREATE TRIGGER {name} AFTER {operation} ON {table} FOR EACH ROW{condition}\n"
            f"EXECUTE FUNCTION qyj_emit_replan_event('{event_type}','{trace}','{task}');")


def generate():
    for path in sorted(ROOT.glob("0[0-9][0-9]_*.sql")):
        source = path.read_text(encoding="utf-8")
        sql = re.sub(r"CREATE TABLE IF NOT EXISTS (\w+) \((.*?)\) ENGINE=InnoDB;", table_ddl, source, flags=re.S)
        sql = re.sub(r"DROP TRIGGER IF EXISTS \w+;\s*", "", sql)
        sql = re.sub(
            r"CREATE TRIGGER (\w+) AFTER (INSERT|UPDATE) ON (\w+) FOR EACH ROW INSERT INTO banking_replan_events\(.+?\) SELECT NEW.user_id,UUID\(\),'([^']+)',CAST\(NEW.id AS CHAR\),'[^']+',(NEW.trace_id|''),(NEW.task_id|''),.+?;",
            trigger_ddl, sql, flags=re.S,
        )
        sql = sql.replace("INSERT IGNORE INTO", "INSERT INTO")
        if path.name == "007_execution.sql":
            sql = sql.replace("('resource_version',1,TRUE,'high',0,'Sensitive resource terms and versions must still match');", "('resource_version',1,TRUE,'high',0,'Sensitive resource terms and versions must still match')\nON CONFLICT (name) DO NOTHING;")
        if path.name in ("008_skills.sql", "009_skill_traces.sql"):
            sql = sql.replace("ADD COLUMN ", "ADD COLUMN IF NOT EXISTS ")
            sql = re.sub(r"VARCHAR\(64\)", "VARCHAR(64) COLLATE qyj_mysql_ci", sql)
        if path.name == "001_core.sql":
            sql = "-- ICU equality preserves the source's case/accent insensitive keys.\nCREATE COLLATION IF NOT EXISTS qyj_mysql_ci (provider = icu, locale = 'und-u-ks-level1', deterministic = false);\n" + sql
        if path.name == "005_planning.sql":
            pos = sql.index("CREATE TRIGGER ")
            sql = sql[:pos] + TRIGGER_FUNCTION + "\n" + sql[pos:]
        header = f"-- Reviewed PostgreSQL equivalent of {path.name}.\n-- Regenerate only with generate_postgres.py; never edit applied baselines.\n"
        (ROOT / ("postgres_" + path.name)).write_text(header + sql, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    generate()

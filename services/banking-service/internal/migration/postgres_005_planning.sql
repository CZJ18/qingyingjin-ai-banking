-- Transactional outbox: a rollback also removes the replan event.
CREATE OR REPLACE FUNCTION qyj_emit_replan_event() RETURNS trigger
LANGUAGE plpgsql AS $qyj$
DECLARE
 event_time BIGINT := floor(extract(epoch FROM clock_timestamp()) * 1000)::BIGINT;
BEGIN
 -- Only the control-table owner (or a member of that owner role) may suppress
 -- derived events during an audited import. A runtime-set custom GUC alone
 -- does not authorize bypass, and the control relation uses the trigger's
 -- schema rather than a caller-controlled search_path or temporary table.
 IF current_setting('banking.migration_import',true)='on' AND
    pg_has_role(session_user,pg_get_userbyid((SELECT relowner FROM pg_class
      WHERE oid=to_regclass(format('%I.banking_storage_control',TG_TABLE_SCHEMA)))),'MEMBER') THEN
   RETURN NEW;
 END IF;
 INSERT INTO banking_replan_events(user_id,event_key,type,resource_id,reason,trace_id,task_id,created_at,updated_at)
 VALUES (NEW.user_id,gen_random_uuid()::TEXT,TG_ARGV[0],NEW.id::TEXT,TG_TABLE_NAME || ':' || lower(TG_OP),
         CASE WHEN TG_ARGV[1]='trace_id' THEN to_jsonb(NEW)->>'trace_id' ELSE '' END,
         CASE WHEN TG_ARGV[2]='task_id' THEN to_jsonb(NEW)->>'task_id' ELSE '' END,event_time,event_time);
 RETURN NEW;
END;
$qyj$;

CREATE TRIGGER qyj_replan_bank_accounts_insert AFTER INSERT ON banking_bank_accounts FOR EACH ROW
EXECUTE FUNCTION qyj_emit_replan_event('account_changed','','');

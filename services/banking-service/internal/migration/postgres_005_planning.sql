 attempts BIGINT NOT NULL DEFAULT 0,
 retry_at BIGINT NOT NULL DEFAULT 0,
 error_code VARCHAR(64) COLLATE qyj_mysql_ci NOT NULL DEFAULT '',
 trace_id VARCHAR(128) COLLATE qyj_mysql_ci NOT NULL DEFAULT '',
 task_id VARCHAR(128) COLLATE qyj_mysql_ci NOT NULL DEFAULT '',
 created_at BIGINT NOT NULL,
 updated_at BIGINT NOT NULL,
 CONSTRAINT replan_events_uq_replan_key UNIQUE (user_id,event_key),
 CONSTRAINT replan_events_uq_replan_owner UNIQUE (user_id,id),
 CONSTRAINT fk_replan_user FOREIGN KEY(user_id) REFERENCES banking_users(id)
);
CREATE INDEX replan_events_ix_replan_pending ON banking_replan_events (status,retry_at,id);
CREATE TABLE IF NOT EXISTS banking_plan_versions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
 user_id BIGINT NOT NULL,
